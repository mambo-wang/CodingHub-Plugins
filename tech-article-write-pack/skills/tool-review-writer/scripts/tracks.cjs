function detectTrack(headingLines) {
  const hits = {};
  for (const t of Object.keys(TRACKS)) {
    const titles = TRACKS[t].sections.map(([h]) => h.replace(/^\d+\.\s*/, ''));
    hits[t] = headingLines.filter((h) => titles.some((title) => h.includes(title))).length;
  }
  return Object.entries(hits).sort((x, y) => y[1] - x[1])[0][0];
}

module.exports = { TRACKS, detectTrack };
